  await p.locator('.modal', { hasText: 'More than the balance' }).getByRole('button', { name: 'Cancel' }).click(); await p.waitForTimeout(200);
  await p.locator('.modal').getByRole('button', { name: 'Cancel' }).click(); await p.waitForTimeout(200);
  ok((await p.locator('.modal').count()) === 0, 'dialogs closed');
