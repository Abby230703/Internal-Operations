  ok((await p.textContent('.drawer .pw-sum')).includes('6,752.00'), 'balance 10,752 - 4,000 = 6,752');
  await p.getByRole('button', { name: 'Close', exact: true }).last().click(); await p.waitForTimeout(300);
  await p.getByRole('button', { name: /^To pay/ }).click(); await p.waitForTimeout(400);
  ok((await p.textContent(vis + ' table.t tbody')).includes('6,752'), 'To pay list shows the balance');

  console.log('accounts: payments');
  await p.getByRole('button', { name: /^Payments$/ }).click(); await p.waitForSelector(vis + ' table.t tbody tr');
  ok((await rows(p)) === 3, 'ledger has 3 payments: ' + (await rows(p)));
  ok((await p.locator(vis + ' .stat').count()) === 3, 'ledger totals');
  ok((await p.textContent(vis + ' .stats')).includes('3,158.40') && (await p.textContent(vis + ' .stats')).includes('4,000.00'), 'money in 3,158.40 and out 4,000: ' + (await p.textContent(vis + ' .stats')));
  await shot(p, '56-acc-payments');
  ok((await p.getByRole('button', { name: 'Delete' }).count()) === 0, 'Accounts has no Delete button');
  await p.getByRole('button', { name: 'Money out' }).click(); await p.waitForTimeout(400);
  ok((await rows(p)) === 1, 'Money out filter shows 1');
  const dl = p.waitForEvent('download');
  await p.getByRole('button', { name: 'Download' }).click();
  const d = await dl; ok(/^payments-\d{4}-\d{2}-\d{2}\.csv$/.test(d.suggestedFilename()), 'csv download: ' + d.suggestedFilename());
  await p.getByRole('button', { name: 'Correct' }).first().click(); await p.waitForSelector('.modal');
  await p.locator('.modal input[type=number]').fill('4500');
  await p.locator('.modal').getByRole('button', { name: 'Save changes' }).click(); await p.waitForTimeout(600);
  ok((await toasts(p)).some(t => /Payment corrected/.test(t)), 'correction toast: ' + (await toasts(p)));
  ok((await p.textContent(vis + ' table.t tbody')).includes('4,500.00'), 'ledger shows the corrected amount');

  console.log('accounts: audit tab');
  await p.getByRole('button', { name: /^Stock audit/ }).click(); await p.waitForTimeout(500);
  ok((await p.textContent('#path')).trim() === 'Accounts / Stock audit', 'audit breadcrumb');
  ok((await p.locator(vis + ' .quick').count()) === 0, 'Accounts does not see the count form');
  await shot(p, '57-acc-audit');
  noErr(p, 'accounts');

  console.log('accounts on a phone');
  await p.close();
  p = await open(browser, 'accounts', 'acc@x.com', 390, 800);
  await p.waitForSelector(vis + ' .empty, ' + vis + ' table.t tbody tr');
  await shot(p, '58-acc-mobile');
  ok(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2), 'no sideways scrolling on a phone');
  await p.getByRole('button', { name: /^Purchase receipts/ }).click(); await p.waitForTimeout(500);
  await p.getByRole('button', { name: /^To pay/ }).click(); await p.waitForTimeout(400);
  await p.getByRole('button', { name: 'Pay', exact: true }).first().click(); await p.waitForSelector('.drawer .card'); await p.waitForTimeout(300);
  await shot(p, '59-acc-mobile-drawer');
  ok(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2), 'no sideways scrolling in the drawer');
  await p.close();

  console.log('admin');
  p = await open(browser, 'admin', 'admin@x.com');
  ok((await tabs(p)).join('|').replace(/\d+/g, '#') === 'Overview#|Products|Users|Locations' || (await tabs(p)).join('|').replace(/\d+/g, '#') === 'Overview|Products|Users|Locations', 'admin tabs: ' + (await tabs(p)).join('|'));
  ok((await p.textContent('#path')).trim() === 'Admin / Overview', 'breadcrumb: ' + (await p.textContent('#path')));
  await p.waitForSelector(vis + ' .stat'); await p.waitForTimeout(500);
  ok((await p.locator(vis + ' .stat').count()) === 8, 'eight department cards');
  ok((await p.locator(vis + ' .pw-ex').count()) >= 1, 'exceptions are listed');
  ok((await p.locator(vis + ' a', { hasText: 'open' }).count()) >= 3, 'links to the departments');
  await shot(p, '60-admin-overview');
  await p.getByRole('button', { name: 'Run sheet check' }).click(); await p.waitForSelector(vis + ' table.t tbody tr');
  ok((await p.textContent(vis)).includes('Payments'), 'sheet check lists the Payments tab');
  await shot(p, '61-admin-check');

  console.log('admin: products');
  await p.getByRole('button', { name: /^Products/ }).click(); await p.waitForSelector(vis + ' table.t tbody tr');
  ok((await rows(p)) === 6, 'six items need details at the start: ' + (await rows(p)));
  await shot(p, '62-admin-products');
  await p.locator(vis + ' tbody tr').first().getByRole('button', { name: 'Edit', exact: true }).click(); await p.waitForSelector('.drawer .card'); await p.waitForTimeout(200);
  await p.locator('.drawer input[placeholder="Name as shown to customers"]').fill('Test catalog name');
  await p.locator('.drawer input[placeholder="Rs per piece, before GST"]').fill('45');
  await p.locator('.drawer input[placeholder="12"]').fill('12');
  await p.locator('.drawer input[placeholder="4 to 8 digits"]').fill('7013');
  await shot(p, '63-admin-product-drawer');
  await p.getByRole('button', { name: 'Save item' }).click(); await p.waitForTimeout(700);
  ok((await toasts(p)).some(t => /Saved /.test(t)), 'item saved: ' + (await toasts(p)));
  ok((await rows(p)) === 5, 'saved item leaves "Needs details": ' + (await rows(p)));
  await p.getByRole('button', { name: /^All$/ }).click(); await p.waitForTimeout(400);
  await p.locator(vis + ' thead input[type=checkbox]').check();
  ok(await p.locator(vis + ' .pw-bar').isVisible(), 'bulk bar appears');
  await p.getByRole('button', { name: 'Mark as checked' }).click(); await p.waitForTimeout(600);
  ok((await toasts(p)).some(t => /6 items marked as checked/.test(t)), 'bulk verify: ' + (await toasts(p)));
  ok((await p.locator(vis + ' .pw-tick').count()) === 6, 'all six show Checked');
  await p.getByRole('button', { name: '+ New item' }).click(); await p.waitForSelector('.modal');
  await p.locator('.modal input[placeholder="Item code"]').fill('777001');
  await p.locator('.modal input[placeholder="Name"]').fill('NEW TEST ITEM');
  await p.locator('.modal').getByRole('button', { name: 'Add item' }).click(); await p.waitForSelector('.drawer .card', { timeout: 4000 }); await p.waitForTimeout(300);
  ok((await p.textContent('.drawer-h h2')).includes('777001') || (await p.textContent('.drawer-h h2')).includes('NEW TEST ITEM'), 'new item opens in the editor');
  await p.keyboard.press('Escape');

  console.log('admin: users');
  await p.getByRole('button', { name: /^Users/ }).click(); await p.waitForSelector(vis + ' table.t tbody tr');
  ok((await rows(p)) === 6, 'six users listed: ' + (await rows(p)));
  ok((await p.locator(vis + ' tbody tr', { hasText: 'Ada Admin' }).getByRole('button', { name: 'Remove' }).count()) === 0, 'you cannot remove yourself');
  await shot(p, '64-admin-users');
  await p.locator(vis + ' input[type=email]').fill('new.person@gmail.com');
  await p.locator(vis + ' .card input[type=text]').first().fill('New Person');
  await p.locator(vis + ' .card select').selectOption('Accounts');
  await p.getByRole('button', { name: 'Add person' }).click(); await p.waitForTimeout(600);
  ok((await rows(p)) === 7, 'person added: ' + (await rows(p)));
  ok((await p.textContent(vis + ' tbody')).includes('new.person@gmail.com'), 'listed with their email');
  await p.locator(vis + ' tbody tr', { hasText: 'New Person' }).getByRole('button', { name: 'Remove' }).click();
  await p.locator('.modal').getByRole('button', { name: 'Remove' }).click(); await p.waitForTimeout(600);
  ok((await rows(p)) === 6, 'person removed');

  console.log('admin: locations');
  await p.getByRole('button', { name: /^Locations/ }).click(); await p.waitForSelector(vis + ' table.t tbody tr');
  ok((await rows(p)) === 3, 'three locations: ' + (await rows(p)));
  await p.locator(vis + ' input[placeholder="FL2-ZB-S2"]').fill('fl2-zc');
  await p.locator(vis + ' input[placeholder="Floor 2, Zone B, Shelf 2"]').fill('Floor 2, Zone C');
  await p.getByRole('button', { name: 'Add location' }).click(); await p.waitForTimeout(600);
  ok((await rows(p)) === 4 && (await p.textContent(vis + ' tbody')).includes('FL2-ZC'), 'location added, code upper-cased');
  await shot(p, '65-admin-locations');
  noErr(p, 'admin');
  await p.close();

  console.log('role walls in the browser');
  p = await open(browser, 'admin', 'acc@x.com');   // Accounts asks for the admin URL -> gets its own department
  ok((await p.textContent('#dept-btn')).includes('Accounts'), 'an Accounts user who asks for ?dept=admin still gets Accounts');
  await p.close();
  p = await open(browser, 'accounts', 'wh@x.com');
  ok((await p.textContent('#dept-btn')).includes('Warehouse'), 'a Warehouse user who asks for ?dept=accounts still gets Warehouse');
  ok(!(await tabs(p)).some(t => /receipts/i.test(t)), 'and sees no money tabs');
