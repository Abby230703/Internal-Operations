  await p.getByRole('button', { name: /^Purchase receipts/ }).click(); await p.waitForSelector(vis + ' table.t tbody tr');
  ok((await p.textContent('#path')).trim() === 'Accounts / Purchase receipts', 'breadcrumb follows the tab');
  ok((await p.textContent(vis + ' table.t tbody')).includes('AE/GRN/0001'), 'received delivery listed under To bill');
  await shot(p, '54-acc-bills');
  await p.getByRole('button', { name: 'Add bill', exact: true }).first().click(); await p.waitForSelector('.drawer .card'); await p.waitForTimeout(200);
  ok((await p.textContent('.drawer .note')).includes('6 pieces arrived damaged'), 'damaged pieces are flagged: ' + (await p.textContent('.drawer .note')));
  ok((await p.textContent('.drawer .pw-sum')).includes('10,752.00'), 'values: 20 sets x 12 x 40 x 1.12 = 10,752: ' + (await p.textContent('.drawer .pw-sum')));
  await shot(p, '55-acc-bill-drawer');
  await p.locator('.drawer input[placeholder="Tally purchase voucher number"]').fill('PV/0009');
  await p.getByRole('button', { name: 'Save bill' }).click(); await p.waitForTimeout(600);
  ok((await toasts(p)).some(t => /Bill saved for AE\/GRN\/0001/.test(t)), 'bill saved: ' + (await toasts(p)));
  await clearToasts(p);
  await p.getByRole('button', { name: 'Pay supplier' }).click(); await p.waitForSelector('.modal');
  await p.locator('.modal input[type=number]').fill('4000');
  await p.locator('.modal select').selectOption('Cheque');
  await p.locator('.modal input[placeholder^="UTR"]').fill('CHQ 000123');
  await p.locator('.modal').getByRole('button', { name: 'Pay', exact: true }).click(); await p.waitForTimeout(700);
